/* ============================== РЕЛИЗ final06 · ВОГНУТЫЙ УГОЛ ДВУХ КОРОБОК: ГЕРОЙ НЕ ОСТАЁТСЯ ВНУТРИ (аудит, бот tsec_sweep, «большой кадр») ==============================
   collideXZ() выталкивает героя из коробок по очереди, один проход. У вогнутого угла двух стыкующихся коробок (две коробки в «Эпилоге», невидимая стена коридора 2-2)
   выталкивание из второй загоняло героя обратно в первую, и он оставался внутри на часть радиуса. Теперь, если после прохода герой всё ещё внутри чего-то,
   проход повторяется (до двух раз): углу хватает двух. Вне угла (нет пересечения после первого прохода) ничего не меняется. */
{const _c=collideXZ;
  collideXZ=function(x,z,r,feet,top,skipMovers){let res=_c(x,z,r,feet,top,skipMovers);
    if(res.hit)for(let k=0;k<2;k++){const q=_c(res.x,res.z,r,feet,top,skipMovers);if(!q.hit)break;res={x:q.x,z:q.z,hit:true};}
    return res;};}
