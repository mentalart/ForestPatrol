def words(t): return [w for w in re.sub(r'\{\w+\}','',t).split() if re.search(r'[A-Za-zА-Яа-яЁё0-9]',w)]
def guard(t):
    ws=[re.sub(r'[^A-Za-zА-Яа-яЁё0-9]','',w).lower() for w in plain(t).split(' ')]
    return ' '.join([w for w in ws if w and not re.fullmatch(r'[a-z]',w) and w not in('пробел','shift','enter','wasd')][:7])
def plain(t): return re.sub(r'\s+',' ',re.sub(r'<[^>]*>','',re.sub(r'<br\s*/?>',' ',str(t)))).strip()
def resolve(objs,key):
    """Ключ записи: номер задачи или слова из её полного текста (без кнопок и знаков, регистр не важен) — ключ по смыслу:
    задачи переставили — запись найдёт свою. -1 — нет такой задачи, -2 — слова есть у нескольких."""
    if isinstance(key,int): return key
    k=' '.join(guard_words(key));hit=[i for i,o in enumerate(objs) if k in ' '.join(guard_words(plain(o)))]
    return hit[0] if len(hit)==1 else (-1 if not hit else -2)
def guard_words(t): return [w for w in (re.sub(r'[^A-Za-zА-Яа-яЁё0-9]','',w).lower() for w in str(t).split(' ')) if w]
def build():
    st=json.load(open(os.path.join(HERE,'data','level_static.json'),encoding='utf-8'))
    out={};bad=[]
    for lv,rows in SHORT.items():
        if lv not in st: bad.append(('нет уровня',lv));continue
        objs=st[lv]['obj'][0];lst=[]
        for idx,s in sorted(rows.items(),key=lambda kv:resolve(objs,kv[0])):
            idx=resolve(objs,idx)
            if idx<0: bad.append(('нет задачи' if idx==-1 else 'ключ подходит к нескольким задачам',lv,s));continue
            if idx>=len(objs): bad.append(('нет задачи',lv,idx));continue
            n=len(words(s))
            if n>12: bad.append(('длиннее 12 слов',lv,idx,n,s))
            for tk in re.findall(r'\{(\w+)\}',s):
                if tk not in TOKENS: bad.append(('метка',lv,idx,tk))
            full=plain(objs[idx])
            if len(words(full))<=n+2: bad.append(('не короче полного текста',lv,idx,len(words(full)),n))
            lst.append([idx,guard(full),s])
        objs2=st[lv]['obj'][1]
        for idx,s in sorted(SHORT_P2.get(lv,{}).items(),key=lambda kv:resolve(objs2,kv[0])):
            idx=resolve(objs2,idx)
            if idx<0: bad.append(('нет задачи у второго игрока' if idx==-1 else 'ключ подходит к нескольким задачам второго игрока',lv,s));continue
            if idx>=len(objs2): bad.append(('нет задачи у второго игрока',lv,idx));continue
            n=len(words(s))
            if n>12: bad.append(('длиннее 12 слов',lv,idx,n,s))
            for tk in re.findall(r'\{(\w+)\}',s):
                if tk not in TOKENS: bad.append(('метка',lv,idx,tk))
            lst.append([idx,guard(plain(objs2[idx])),s])
