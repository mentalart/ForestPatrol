def words(t): return [w for w in re.sub(r'\{\w+\}','',t).split() if re.search(r'[A-Za-zА-Яа-яЁё0-9]',w)]
def guard(t):
    ws=[re.sub(r'[^A-Za-zА-Яа-яЁё0-9]','',w).lower() for w in plain(t).split(' ')]
    return ' '.join([w for w in ws if w and not re.fullmatch(r'[a-z]',w) and w not in('пробел','shift','enter','wasd')][:7])
def plain(t): return re.sub(r'\s+',' ',re.sub(r'<[^>]*>','',re.sub(r'<br\s*/?>',' ',str(t)))).strip()
def build():
    st=json.load(open(os.path.join(HERE,'data','level_static.json'),encoding='utf-8'))
    out={};bad=[]
    for lv,rows in SHORT.items():
        if lv not in st: bad.append(('нет уровня',lv));continue
        objs=st[lv]['obj'][0];lst=[]
        for idx,s in sorted(rows.items()):
            if idx>=len(objs): bad.append(('нет задачи',lv,idx));continue
            n=len(words(s))
            if n>12: bad.append(('длиннее 12 слов',lv,idx,n,s))
            for tk in re.findall(r'\{(\w+)\}',s):
                if tk not in TOKENS: bad.append(('метка',lv,idx,tk))
            full=plain(objs[idx])
            if len(words(full))<=n+2: bad.append(('не короче полного текста',lv,idx,len(words(full)),n))
            lst.append([idx,guard(full),s])
        for idx,s in sorted(SHORT_P2.get(lv,{}).items()):
            objs2=st[lv]['obj'][1]
            if idx>=len(objs2): bad.append(('нет задачи у второго игрока',lv,idx));continue
            n=len(words(s))
            if n>12: bad.append(('длиннее 12 слов',lv,idx,n,s))
            for tk in re.findall(r'\{(\w+)\}',s):
                if tk not in TOKENS: bad.append(('метка',lv,idx,tk))
            lst.append([idx,guard(plain(objs2[idx])),s])
        gs=[r[1] for r in lst]
        for g in set(gs):
            if len({r[2] for r in lst if r[1]==g})>1: bad.append(('охрана повторяется',lv,g))
        out[lv]=lst
    return out,bad
